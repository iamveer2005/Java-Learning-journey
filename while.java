package loops;

//this program shows the using of while loop 
class WhileDemo {
    public static void main(String[] args) {

    // Declare the value of i as 0
        int i = 0;
    // while(i < 11) means that value of i should be less than 11
        while (i<11)  {
            System.out.println(i);
    // increse the value of i by 1 every time until it reaches 12 at 12 it will show error and loop will end
            i = i + 1;
        }
        }
    }
